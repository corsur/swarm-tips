function schemaToTs(schema) {
  if (!schema || typeof schema !== "object") {
    return "unknown";
  }
  if (typeof schema.$ref === "string") {
    const prefix = "#/components/schemas/";
    if (schema.$ref.startsWith(prefix)) {
      const refName = schema.$ref.slice(prefix.length);
      return `OpenApiSchemas[${JSON.stringify(refName)}]`;
    }
    return "unknown";
  }
  if (Array.isArray(schema.enum) && schema.enum.length > 0) {
    return schema.enum.map((v) => JSON.stringify(v)).join(" | ");
  }
  if (Array.isArray(schema.oneOf) && schema.oneOf.length > 0) {
    return schema.oneOf.map((s) => `(${schemaToTs(s)})`).join(" | ");
  }
  if (Array.isArray(schema.anyOf) && schema.anyOf.length > 0) {
    return schema.anyOf.map((s) => `(${schemaToTs(s)})`).join(" | ");
  }
  if (Array.isArray(schema.allOf) && schema.allOf.length > 0) {
    return schema.allOf.map((s) => `(${schemaToTs(s)})`).join(" & ");
  }

  const rawType = schema.type;
  if (Array.isArray(rawType)) {
    return rawType
      .map((t) => schemaToTs({ ...schema, type: t }))
      .join(" | ");
  }

  switch (rawType) {
    case "string":
      return "string";
    case "integer":
    case "number":
      return "number";
    case "boolean":
      return "boolean";
    case "null":
      return "null";
    case "array":
      return `Array<${schemaToTs(schema.items)}>`;
    case "object": {
      const props = schema.properties ?? {};
      const propKeys = Object.keys(props).sort();
      const requiredSet = new Set(
        Array.isArray(schema.required) ? schema.required : []
      );
      if (propKeys.length === 0) {
        if (
          schema.additionalProperties &&
          typeof schema.additionalProperties === "object"
        ) {
          return `Record<string, ${schemaToTs(schema.additionalProperties)}>`;
        }
        return "Record<string, unknown>";
      }
      const fields = propKeys.map((k) => {
        const opt = requiredSet.has(k) ? "" : "?";
        return `${JSON.stringify(k)}${opt}: ${schemaToTs(props[k])};`;
      });
      return `{ ${fields.join(" ")} }`;
    }
    default: {
      if (schema.properties && typeof schema.properties === "object") {
        return schemaToTs({ ...schema, type: "object" });
      }
      return "unknown";
    }
  }
}

function extractOperationTypes(op) {
  const params = Array.isArray(op.parameters) ? op.parameters : [];
  const pathParams = params.filter((p) => p?.in === "path");
  const queryParams = params.filter((p) => p?.in === "query");

  const renderParamGroup = (list) => {
    if (list.length === 0) return "never";
    const fields = list.map((p) => {
      const opt = p.required ? "" : "?";
      return `${JSON.stringify(p.name)}${opt}: ${schemaToTs(p.schema)};`;
    });
    return `{ ${fields.join(" ")} }`;
  };

  const reqSchema = op.requestBody?.content?.["application/json"]?.schema;
  const reqType = reqSchema ? schemaToTs(reqSchema) : "never";

  const responses = op.responses ?? {};
  const okResp =
    responses["200"] ?? responses["201"] ?? responses["202"] ?? null;
  const respSchema = okResp?.content?.["application/json"]?.schema;
  const respType = respSchema ? schemaToTs(respSchema) : "unknown";

  const serverUrl = op.servers?.[0]?.url ?? "https://mcp.swarm.tips";

  return {
    serverUrl,
    pathParams: renderParamGroup(pathParams),
    queryParams: renderParamGroup(queryParams),
    requestBody: reqType,
    response: respType,
  };
}

function generateOpenApiTs(mergedSpecPath) {
  const spec = JSON.parse(readFileSync(mergedSpecPath, "utf8"));
  const schemas = spec.components?.schemas ?? {};
  const paths = spec.paths ?? {};
  const servers = (spec.servers ?? []).map((s) => s.url);

  const lines = [
    "// AUTO-GENERATED by scripts/sync-generated.mjs from services/mcp-server/openapi.merged.json.",
    "// Do not edit by hand — run `pnpm --filter @swarm-tips/client sync:generated`.",
    "",
    `export const OPENAPI_VERSION = ${JSON.stringify(
      spec.info?.version ?? pkg.version
    )} as const;`,
    `export const OPENAPI_SERVERS = ${JSON.stringify(servers)} as const;`,
    "export type OpenApiServerUrl = (typeof OPENAPI_SERVERS)[number];",
    "",
    "export interface OpenApiSchemas {",
  ];

  for (const name of Object.keys(schemas).sort()) {
    lines.push(`  ${JSON.stringify(name)}: ${schemaToTs(schemas[name])};`);
  }
  lines.push("}", "");

  const operations = [];
  lines.push("export interface OpenApiPaths {");
  for (const pathKey of Object.keys(paths).sort()) {
    const item = paths[pathKey];
    lines.push(`  ${JSON.stringify(pathKey)}: {`);
    for (const method of ["get", "post", "put", "patch", "delete"]) {
      const op = item?.[method];
      if (!op || typeof op !== "object") continue;
      const opId = op.operationId;
      const types = extractOperationTypes(op);
      operations.push({ opId, method: method.toUpperCase(), pathKey, ...types });
      lines.push(
        `    ${JSON.stringify(method)}: OpenApiOperations[${JSON.stringify(
          opId
        )}];`
      );
    }
    lines.push("  };");
  }
  lines.push("}", "");

  operations.sort((a, b) => a.opId.localeCompare(b.opId));
  lines.push("export interface OpenApiOperations {");
  for (const op of operations) {
    lines.push(`  ${JSON.stringify(op.opId)}: {`);
    lines.push(`    method: ${JSON.stringify(op.method)};`);
    lines.push(`    path: ${JSON.stringify(op.pathKey)};`);
    lines.push(`    server: ${JSON.stringify(op.serverUrl)};`);
    lines.push(`    params: { path: ${op.pathParams}; query: ${op.queryParams} };`);
    lines.push(`    requestBody: ${op.requestBody};`);
    lines.push(`    response: ${op.response};`);
    lines.push("  };");
  }
  lines.push("}", "");
  lines.push("export type OpenApiOperationId = keyof OpenApiOperations;");
  lines.push("");

  const rawTs = lines.join("\n");
  return Buffer.from(
    prettier.format(rawTs, { parser: "typescript" }),
    "utf8"
  );
}

const versionRelPath = "src/version.ts";
const versionAbsPath = resolve(packageRoot, versionRelPath);
const expectedVersionContents = Buffer.from(
  `export const CLIENT_VERSION = ${JSON.stringify(pkg.version)};\n`,
  "utf8"
);

const openapiMergedSourcePath = resolve(
  repositoryRoot,
  "services/mcp-server/openapi.merged.json"
);
const openapiRelPath = "src/generated/openapi.ts";
const openapiAbsPath = resolve(packageRoot, openapiRelPath);

const digest = (contents) =>
  createHash("sha256").update(contents).digest("hex");
const expectedDigests =
  check && existsSync(manifestPath)
    ? JSON.parse(readFileSync(manifestPath, "utf8"))
    : {};
const generatedDigests = {};
let stale = false;
for (const [sourceName, destinationName] of files) {
  const sourcePath = resolve(repositoryRoot, sourceName);
  const destinationPath = resolve(packageRoot, destinationName);
  if (check) {
    let destination = Buffer.alloc(0);
    try {
      destination = readFileSync(destinationPath);
    } catch {
      // Report the same actionable stale message below.
    }
    const expected = expectedDigests[destinationName];
    if (!expected || digest(destination) !== expected) {
      console.error(
        `${destinationName} does not match scripts/generated-bindings.json; ` +
          "run pnpm sync:generated after building both programs"
      );
      stale = true;
    }
    if (existsSync(sourcePath)) {
      const source = readFileSync(sourcePath);
      if (!source.equals(destination)) {
        console.error(
          `${destinationName} is stale against ${sourceName}; ` +
            "run pnpm sync:generated after building both programs"
        );
        stale = true;
      }
    }
  } else {
    const source = existsSync(sourcePath)
      ? readFileSync(sourcePath)
      : readFileSync(destinationPath);
    writeFileSync(destinationPath, source);
    generatedDigests[destinationName] = digest(source);
    console.log(`updated ${destinationName}`);
  }
}

const expectedOpenApiContents = existsSync(openapiMergedSourcePath)
  ? generateOpenApiTs(openapiMergedSourcePath)
  : existsSync(openapiAbsPath)
  ? readFileSync(openapiAbsPath)
  : Buffer.alloc(0);

if (check) {
  let currentVersionFile = Buffer.alloc(0);
  try {
    currentVersionFile = readFileSync(versionAbsPath);
  } catch {
    // Handled below.
  }
  const expectedDigest = expectedDigests[versionRelPath];
  if (
    !currentVersionFile.equals(expectedVersionContents) ||
    !expectedDigest ||
    digest(currentVersionFile) !== expectedDigest
  ) {
    console.error(
      `${versionRelPath} does not match package.json (${pkg.version}); ` +
        "run pnpm --filter @swarm-tips/client sync:generated"
    );
    stale = true;
  }

  let currentOpenApiFile = Buffer.alloc(0);
  try {
    currentOpenApiFile = readFileSync(openapiAbsPath);
  } catch {
    // Handled below.
  }
  const expectedOpenApiDigest = expectedDigests[openapiRelPath];
  if (
    !currentOpenApiFile.equals(expectedOpenApiContents) ||
    !expectedOpenApiDigest ||
    digest(currentOpenApiFile) !== expectedOpenApiDigest
  ) {
    console.error(
      `${openapiRelPath} is stale against services/mcp-server/openapi.merged.json; ` +
        "run pnpm --filter @swarm-tips/client sync:generated"
    );
    stale = true;
  }
} else {
  writeFileSync(versionAbsPath, expectedVersionContents);
  generatedDigests[versionRelPath] = digest(expectedVersionContents);
  console.log(`updated ${versionRelPath}`);

  mkdirSync(dirname(openapiAbsPath), { recursive: true });
  writeFileSync(openapiAbsPath, expectedOpenApiContents);
  generatedDigests[openapiRelPath] = digest(expectedOpenApiContents);
  console.log(`updated ${openapiRelPath}`);

  writeFileSync(
    manifestPath,
    `${JSON.stringify(generatedDigests, null, 2)}\n`
  );
  console.log("updated scripts/generated-bindings.json");
}

if (stale) process.exit(1);
